#!/bin/sh

set -eu
PATH="/usr/local/bin:/usr/local/sbin:/usr/bin:/usr/sbin:/bin:/sbin${PATH:+:$PATH}"

action="${1:-snapshot}"
profile_file="${BSDRUNNER_POWER_PROFILE_FILE:-${HOME}/.config/bsdrunner/power/profile.conf}"
idle_config="${BSDRUNNER_HYPRIDLE_CONFIG:-${HOME}/.config/hypr/hypridle.conf}"
lock_script="${BSDRUNNER_LOCK_SCRIPT:-${HOME}/.config/bsdrunner/scripts/bsdrunner-lock.sh}"
start_script="${BSDRUNNER_IDLE_START_SCRIPT:-${HOME}/.config/bsdrunner/scripts/bsdrunner-start-idle.sh}"
idle_log="${BSDRUNNER_HYPRIDLE_LOG:-/tmp/bsdrunner-hypridle.log}"

lock_enabled="yes"
lock_timeout_minutes="15"

normalize_bool() {
    case "$(printf '%s' "${1:-}" | tr '[:upper:]' '[:lower:]')" in
        1|yes|true|on|enabled)
            printf 'yes\n'
            ;;
        *)
            printf 'no\n'
            ;;
    esac
}

valid_timeout() {
    case "${1:-}" in
        ''|*[!0-9]*)
            return 1
            ;;
    esac

    [ "$1" -ge 1 ] && [ "$1" -le 120 ]
}

json_escape() {
    awk '
        BEGIN { first = 1 }
        {
            gsub(/\\/, "\\\\")
            gsub(/"/, "\\\"")
            gsub(/\r/, "")
            if (!first)
                printf "\\n"
            printf "%s", $0
            first = 0
        }
    '
}

bool_json() {
    [ "$1" = "yes" ] && printf true || printf false
}

idle_running() {
    # FreeBSD's pgrep includes zombie processes. Only a runnable/sleeping
    # hypridle process means the idle timer is actually active.
    ps ax -o stat= -o comm= 2>/dev/null | awk '
        $1 !~ /^Z/ && $2 == "hypridle" { found = 1; exit }
        END { exit found ? 0 : 1 }
    '
}

load_profile() {
    [ -f "$profile_file" ] || return 0

    while IFS='=' read -r key value; do
        case "$key" in
            lock_enabled)
                lock_enabled="$(normalize_bool "$value")"
                ;;
            lock_timeout_minutes)
                if valid_timeout "$value"; then
                    lock_timeout_minutes="$value"
                fi
                ;;
        esac
    done <"$profile_file"
}

write_profile() {
    mkdir -p "$(dirname "$profile_file")"
    {
        printf 'lock_enabled=%s\n' "$lock_enabled"
        printf 'lock_timeout_minutes=%s\n' "$lock_timeout_minutes"
    } >"$profile_file"
}

render_idle_config() {
    timeout_seconds=$((lock_timeout_minutes * 60))
    mkdir -p "$(dirname "$idle_config")"
    cat >"$idle_config" <<EOF
# Generated by BSDRunner Power Settings.
# Edit ~/.config/bsdrunner/power/profile.conf through the GUI instead.

general {
    lock_cmd = sh $lock_script
    ignore_dbus_inhibit = true
    ignore_systemd_inhibit = true
    ignore_wayland_inhibit = false
}

listener {
    timeout = $timeout_seconds
    on-timeout = sh $lock_script
}
EOF
}

stop_idle() {
    pkill -x hypridle >/dev/null 2>&1 || true

    attempts=0
    while idle_running && [ "$attempts" -lt 20 ]; do
        sleep 0.05
        attempts=$((attempts + 1))
    done
}

start_idle() {
    [ "$lock_enabled" = "yes" ] || return 0
    command -v hypridle >/dev/null 2>&1 || return 1
    command -v hyprlock >/dev/null 2>&1 || return 1

    if [ "${BSDRUNNER_POWER_SKIP_RESTART:-no}" = "yes" ]; then
        return 0
    fi

    sh "$start_script"
    attempts=0
    while ! idle_running && [ "$attempts" -lt 20 ]; do
        sleep 0.05
        attempts=$((attempts + 1))
    done
    idle_running
}

restart_idle() {
    if [ "${BSDRUNNER_POWER_SKIP_RESTART:-no}" != "yes" ]; then
        stop_idle
    fi

    if [ "$lock_enabled" = "yes" ]; then
        start_idle
    fi
}

emit_snapshot() {
    message="${1:-Power settings loaded.}"
    hypridle_installed=no
    hyprlock_installed=no
    idle_running=no

    command -v hypridle >/dev/null 2>&1 && hypridle_installed=yes
    command -v hyprlock >/dev/null 2>&1 && hyprlock_installed=yes
    idle_running && idle_running=yes

    printf '{'
    printf '"ok":true,'
    printf '"message":"%s",' "$(printf '%s' "$message" | json_escape)"
    printf '"enabled":%s,' "$(bool_json "$lock_enabled")"
    printf '"timeout_minutes":%s,' "$lock_timeout_minutes"
    printf '"hypridle_installed":%s,' "$(bool_json "$hypridle_installed")"
    printf '"hyprlock_installed":%s,' "$(bool_json "$hyprlock_installed")"
    printf '"idle_running":%s,' "$(bool_json "$idle_running")"
    printf '"config_path":"%s",' "$(printf '%s' "$idle_config" | json_escape)"
    printf '"log_path":"%s"' "$(printf '%s' "$idle_log" | json_escape)"
    printf '}\n'
}

apply_settings() {
    write_profile
    render_idle_config

    if restart_idle; then
        if [ "$lock_enabled" = "yes" ]; then
            emit_snapshot "Automatic screen locking is active."
        else
            emit_snapshot "Automatic screen locking is disabled."
        fi
        return
    fi

    emit_snapshot "Install hypridle and hyprlock to activate automatic locking."
}

load_profile

case "$action" in
    snapshot)
        emit_snapshot
        ;;
    apply)
        apply_settings
        ;;
    set-timeout)
        requested_timeout="${2:-}"
        valid_timeout "$requested_timeout" || {
            printf '{"ok":false,"message":"Lock timeout must be between 1 and 120 minutes."}\n'
            exit 1
        }
        lock_timeout_minutes="$requested_timeout"
        apply_settings
        ;;
    set-enabled)
        lock_enabled="$(normalize_bool "${2:-no}")"
        apply_settings
        ;;
    *)
        printf '{"ok":false,"message":"Unknown power action: %s"}\n' "$(printf '%s' "$action" | json_escape)"
        exit 1
        ;;
esac
